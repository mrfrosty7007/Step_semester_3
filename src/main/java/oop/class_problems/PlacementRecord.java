package oop.class_problems;

/**
 * Week 6 — S6: Classes and Objects Revision — Practice Problem M1
 * Program: Student Placement Record Management
 * Concepts: Class definition, instance fields, parameterized constructor, instance method, array of objects.
 */
public class PlacementRecord {

    String studentName;
    String company;
    double packageLpa;

    public PlacementRecord(String studentName, String company, double packageLpa) {
        this.studentName = studentName;
        this.company = company;
        this.packageLpa = packageLpa;
    }

    public void printRecord() {
        System.out.println(studentName + " -> " + company + " @ " + packageLpa + " LPA");
    }

    public static void main(String[] args) {
        System.out.println("=== M1. Student Placement Record Management ===");

        PlacementRecord[] records = {
            new PlacementRecord("Ravi", "TCS", 4.5),
            new PlacementRecord("Anitha", "Zoho", 6.2),
            new PlacementRecord("Karthik", "Infosys", 4.0)
        };

        for (PlacementRecord record : records) {
            record.printRecord();
        }
    }
}
